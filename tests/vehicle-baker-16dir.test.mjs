import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createZip } from '../src/vehicle/zip-pack.js';
const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
const baker=fs.readFileSync(path.join(root,'src/vehicle/vehicle-baker.js'),'utf8');
const app=fs.readFileSync(path.join(root,'src/app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const directions=Array.from(baker.matchAll(/\{id:'([A-Z]+)',degrees:(-?\d+(?:\.\d+)?)\}/g));
assert.equal(directions.length,16,'exactly 16 headings');
assert.deepEqual(directions.map(x=>x[1]),['N','NNE','NE','ENE','E','ESE','SE','SSE','S','SSW','SW','WSW','W','WNW','NW','NNW']);
const values=directions.map(x=>+x[2]);
for(let i=0;i<16;i++)assert.equal(((values[i]-values[(i+1)%16])%360+360)%360,22.5);
assert.equal((html.match(/data-vehicle-dir="\d+"/g)||[]).length,16);
assert.match(app,/exportVehicle16Pack/);
assert.match(baker,/finally\s*\{/,'baking restores WebGL state on failure');
assert.match(baker,/shadowCatcher.visible=layer!=='turret'/,'no ghost ground shadow in turret atlas');
assert.match(baker,/oldSceneVisibility/,'background scenery is isolated during bake');
assert.match(baker,/createElement\('canvas'\)/,'actual PNG atlases generated');
assert.match(baker,/hullTurretPivotPxByDirection/);
assert.match(baker,/turretSpritePivotPx/);
const zip=createZip([{name:'hull.png',data:new Uint8Array([137,80,78,71])},{name:'turret.json',data:'{"count":16}'}]);
const bytes=new Uint8Array(await zip.arrayBuffer());
assert.equal(new DataView(bytes.buffer).getUint32(0,true),0x04034b50);
assert.equal(new DataView(bytes.buffer).getUint32(bytes.length-22,true),0x06054b50);
assert.equal(new DataView(bytes.buffer).getUint16(bytes.length-14,true),2);
console.log('Vehicle Baker v0.2: 16 directions, split layers, pivots, transparency isolation, and ZIP writer verified.');
